const assert = require('node:assert/strict');
const crypto = require('node:crypto');
require('@next/env').loadEnvConfig(process.cwd());
const { PrismaClient } = require('@prisma/client');
const { chromium } = require('playwright');
const XLSX = require('xlsx');
const db = new PrismaClient();
const base = 'http://localhost:3002';
const stamp = crypto.randomUUID();
let user, company, browser;
const ids = [];
async function main() {
  assert(['localhost', '127.0.0.1'].includes(new URL(process.env.DATABASE_URL).hostname));
  try {
    const edesur = await db.enrollmentCompany.findFirst({ where: { name: 'EDESUR' } });
    assert(edesur);
    user = await db.user.create({ data: { name: 'Prueba retiros', email: `retiros-${stamp}@example.invalid`, passwordHash: 'test-only', role: 'ADMIN' } });
    company = await db.enrollmentCompany.create({ data: { formId: edesur.formId, name: 'RETIROS ' + stamp, dataUpdateLookupField: 'EMPLOYEE_NUMBER' } });
    const number = '999' + Date.now();
    const create = async (companyId, suffix, employeeNumber) => {
      const member = await db.souvenirMember.create({ data: { enrollmentCompanyId: companyId, firstName: 'RETIROS ' + stamp, lastName: suffix, employeeNumber } });
      ids.push(member.id); return member;
    };
    const collector = await create(edesur.id, 'EMPLEADO EDESUR', number);
    const first = await create(company.id, 'SOCIO UNO', number + '1');
    const second = await create(company.id, 'SOCIO DOS', number + '2');
    const third = await create(company.id, 'SOCIO TRES', number + '3');
    const fourth = await create(company.id, 'SOCIO CUATRO', number + '4');
    const body = Buffer.from(JSON.stringify({ userId: user.id, expiresAt: Date.now() + 600000 })).toString('base64url');
    const cookie = body + '.' + crypto.createHmac('sha256', process.env.AUTH_SECRET || 'edecoop-dev-secret-change-me').update(body).digest('base64url');
    const api = (url, opts = {}) => fetch(base + url, { ...opts, headers: { cookie: 'edecoop_session=' + cookie, 'Content-Type': 'application/json' } });
    const deliver = (member, other = false, employee = number) => api('/api/souvenir', { method: 'POST', body: JSON.stringify({ memberId: member.id, companyId: member.enrollmentCompanyId, collectedByOther: other, collectorEmployeeNumber: employee }) });
    assert.equal((await fetch(base + '/api/souvenir/retira?memberId=' + first.id + '&employeeNumber=' + number)).status, 401);
    assert.equal((await api('/api/souvenir/retira?memberId=' + collector.id + '&employeeNumber=' + number)).status, 422);
    assert.equal((await deliver(first, true, first.employeeNumber)).status, 422);
    assert.equal((await deliver(first, true, 'abc')).status, 422);
    assert.equal((await deliver(first, true, '')).status, 422);
    assert.equal((await deliver(collector)).status, 200);
    assert.equal((await deliver(collector)).status, 409);
    assert.equal((await deliver(first, true)).status, 200);
    assert.equal((await deliver(second, true)).status, 200);
    assert.equal((await deliver(first, true)).status, 409);
    const saved = await db.souvenirDelivery.findUnique({ where: { souvenirMemberId: first.id } });
    assert.equal(saved.collectorEmployeeNumber, number);
    assert.equal(saved.collectorName, collector.firstName + ' ' + collector.lastName);
    assert.equal(saved.collectedByOther, true);
    browser = await chromium.launch({ headless: true, channel: 'msedge' });
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
    await context.addCookies([{ name: 'edecoop_session', value: cookie, url: base }]);
    const page = await context.newPage();
    await page.goto(base + '/entrega-souvenir');
    await page.getByRole('button', { name: 'Entregar Souvenir', exact: true }).click();
    await page.getByRole('dialog').getByRole('combobox').selectOption(company.id);
    await page.getByRole('button', { name: 'Continuar', exact: true }).click();
    await page.getByLabel('Número de empleado', { exact: true }).fill(third.employeeNumber);
    await page.getByRole('button', { name: 'Buscar', exact: true }).click();
    await page.getByRole('dialog', { name: 'Confirmar entrega' }).waitFor();
    await page.getByLabel('Retira otro socio de EDESUR').check();
    assert(await page.getByRole('button', { name: 'Entregado', exact: true }).isDisabled());
    await page.getByLabel('Número de empleado de quien retira', { exact: true }).fill(number);
    await page.getByRole('button', { name: 'Validar empleado' }).click();
    await page.getByRole('status').filter({ hasText: 'EMPLEADO EDESUR' }).waitFor();
    assert(await page.getByRole('button', { name: 'Entregado', exact: true }).isEnabled());
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: 'outputs/souvenir-collector-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1280, height: 900 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: 'outputs/souvenir-collector-desktop.png', fullPage: true });
    await page.getByLabel('Número de empleado de quien retira', { exact: true }).fill(number + '0');
    assert(await page.getByRole('button', { name: 'Entregado', exact: true }).isDisabled());
    await page.getByLabel('Número de empleado de quien retira', { exact: true }).fill(number);
    await page.getByRole('button', { name: 'Validar empleado' }).click();
    await page.getByRole('status').filter({ hasText: 'EMPLEADO EDESUR' }).waitFor();
    await page.getByRole('button', { name: 'Entregado', exact: true }).click();
    await page.getByRole('dialog', { name: 'Buscar socio', exact: true }).waitFor();
    assert.equal(await page.getByLabel('Número de empleado', { exact: true }).inputValue(), '');
    await page.getByLabel('Número de empleado', { exact: true }).fill(fourth.employeeNumber);
    await page.getByRole('button', { name: 'Buscar', exact: true }).click();
    await page.getByRole('dialog', { name: 'Confirmar entrega' }).waitFor();
    assert(!await page.getByLabel('Retira otro socio de EDESUR').isChecked());
    assert.equal(await page.getByLabel('Número de empleado de quien retira', { exact: true }).count(), 0);
    await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
    await page.goto(base + '/entrega-souvenir/estado');
    await page.getByLabel('Empresa', { exact: true }).selectOption(company.id);
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Descargar Excel', exact: true }).click();
    const download = await downloadEvent;
    const workbook = XLSX.readFile(await download.path());
    const exported = XLSX.utils.sheet_to_json(workbook.Sheets.Detalle);
    const exportedFirst = exported.find(row => row['Número de empleado'] === first.employeeNumber);
    assert.equal(exportedFirst['Empleado que retiró'], number);
    assert.equal(exportedFirst['Retiró'], 'Otro socio de EDESUR');
    const history = await (await api('/api/souvenir/listado?view=estado')).json();
    assert.equal(history.members.find(m => m.id === third.id).collectorEmployeeNumber, number);
    await db.souvenirMember.delete({ where: { id: first.id } });
    assert.equal((await (await api('/api/souvenir/listado?view=estado')).json()).members.find(m => m.id === saved.id).collectorName, saved.collectorName);
    console.log('PASS: EDESUR only, self-rejection, own delivery once, multiple delegated deliveries, server checks, mobile validation reset and retained history.');
  } finally {
    if (browser) await browser.close();
    if (user) { await db.auditLog.deleteMany({ where: { userId: user.id } }); await db.souvenirDelivery.deleteMany({ where: { deliveredById: user.id } }); }
    await db.souvenirMember.deleteMany({ where: { id: { in: ids } } });
    if (company) await db.enrollmentCompany.delete({ where: { id: company.id } });
    if (user) await db.user.delete({ where: { id: user.id } });
    await db.$disconnect();
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
